// Turns Win32 keyboard, character, IME and pointer messages into frame input events for one window.
class Win32FrameInput{
public:
    Win32FrameInput(Frame& frame, HWND hwnd)noexcept
        : m_frame(frame)
        , m_hwnd(hwnd)
    {}


public:
    // Returns the window procedure result when the message is an input message handled here.
    [[nodiscard]] Optional<LRESULT> handleMessage(UINT message, WPARAM wParam, LPARAM lParam);
    void dispatchTextInputFocus(bool focused);


private:
    void dispatchUnicodeInput(u32 unicode);
    void captureMouse();
    void releaseMouseIfNoButtonIsDown();
    void dispatchMousePosition(LPARAM lParam);
    void dispatchScreenMousePosition(LPARAM lParam);
    void dispatchKeyEvent(WPARAM wParam, LPARAM lParam, i32 action);
    void dispatchCharInput(WPARAM wParam, LPARAM lParam);


private:
    Frame& m_frame;
    HWND m_hwnd;
};


