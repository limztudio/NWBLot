struct BalancedPartitionRange{
    usize first;
    usize last;
};


[[nodiscard]] inline constexpr BalancedPartitionRange ComputeBalancedPartitionRange(const usize begin, const usize chunk, const usize chunkSize, const usize remainder)noexcept{
    const usize first = begin + chunk * chunkSize + (chunk < remainder ? chunk : remainder);
    return { first, first + chunkSize + (chunk < remainder ? 1u : 0u) };
}


