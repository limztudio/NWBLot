class FloatingPointEnvironmentGuard final : NoCopy{
public:
    explicit FloatingPointEnvironmentGuard(const FloatingPointEnvironment& environment)noexcept
        : m_environment(environment)
    {}
    FloatingPointEnvironmentGuard(FloatingPointEnvironmentGuard&&) = delete;
    ~FloatingPointEnvironmentGuard()noexcept{
        if(m_active && !SetFloatingPointEnvironment(m_environment))
            NWB_ASSERT(false);
    }


public:
    void release()noexcept{ m_active = false; }


private:
    FloatingPointEnvironment m_environment{};
    b8 m_active = true;
};


