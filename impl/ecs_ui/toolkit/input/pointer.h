namespace PointerPhase{
    enum Enum : u8{ Move, Press, Release, Cancel, Leave, Scroll };
};

namespace PointerIntent{
    enum Enum : u8{ Activate, ContextMenu };
};

// Each contact keeps its identity through release or cancellation; hover is an explicit adapter capability.
struct PointerInput{
    InputSource source;
    PointerPhase::Enum phase = PointerPhase::Move;
    PointerIntent::Enum intent = PointerIntent::Activate;
    Point position{};
    f64 scrollX = 0.0;
    f64 scrollY = 0.0;
    u64 timestampMs = 0u;
    bool extend = false;
    bool hoverCapable = false;
};


