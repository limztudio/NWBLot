b8 ReadCompletePayload(const Span<const u8> binary, const usize cursor, const TStringView failureContext){
    if(cursor != binary.size()){
        NWB_LOGGER_ERROR(NWB_TEXT("{} failed: trailing bytes detected"), failureContext);
        return false;
    }

    return true;
}


