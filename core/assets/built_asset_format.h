inline constexpr AStringView s_BuiltAssetExtension = ".nwba";
inline constexpr u32 s_BuiltAssetMagic = 0x4142574eu;
inline constexpr u16 s_BuiltAssetVersion = 2u;
inline constexpr u32 s_BuiltAssetFlagStandalone = 1u << 0u;

struct BuiltAssetFileHeader{
    u32 magic = s_BuiltAssetMagic;
    u16 version = s_BuiltAssetVersion;
    u16 headerSize = sizeof(BuiltAssetFileHeader);
    u32 flags = 0u;
    u32 entryCount = 0u;
    Sha256Digest paramSha256 = {};
    u64 payloadSectionSize = 0u;
    u64 payloadSectionHashFnv64 = 0u;
};
static_assert(sizeof(BuiltAssetFileHeader) == 64u, "BuiltAssetFileHeader must stay compact");

struct BuiltAssetEncodeEntry{
    u32 nwbSubIndex = 0u;
    NameHash assetTypeHash = {};
    Name virtualPath = s_NameNone;
    Span<const u8> payloadBytes;
    u64 payloadHashFnv64 = 0u;
};

struct DecodedBuiltAssetEntryView{
    u32 nwbSubIndex = 0u;
    Name assetType = s_NameNone;
    Name virtualPath = s_NameNone;
    usize payloadOffset = 0u;
    usize payloadSize = 0u;
};

struct DecodedBuiltAssetFileView{
    BuiltAssetFileHeader header;
    AStringView sourcePathText;
};


