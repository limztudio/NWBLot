////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


struct ParsedAttributeArg{
    MStringView text;
    TokenType::Enum kind = TokenType::Identifier;
    u32 line = 1;
    u32 column = 1;
};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


struct ParsedAttribute{
    MStringView name;
    MVector<ParsedAttributeArg> arguments;
    u32 line = 1;
    u32 column = 1;


public:
    explicit ParsedAttribute(MetaArena& arena)noexcept
        : arguments(arena)
    {}
};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


class AttributeParser{
public:
    explicit AttributeParser(ParserCursor& cursor)noexcept
        : m_cursor(cursor)
    {}


public:
    [[nodiscard]] bool parseSingleBracketList(MVector<ParsedAttribute>& outAttributes);


private:
    [[nodiscard]] bool parseAttributeItem(MVector<ParsedAttribute>& outAttributes);


private:
    ParserCursor& m_cursor;
};


