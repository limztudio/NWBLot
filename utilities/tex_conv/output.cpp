bool ResolveOutputPaths(const Path& inputPath, const AStringView outputArgument, OutputPaths& outOutputPaths){
    if(outputArgument.empty()){
        outOutputPaths.metadata = inputPath;
        outOutputPaths.metadata.replaceExtension(__hidden_output::s_NwbOutputExtension);
    }
    else{
        const Path outputBase(UtilityDetail::Arena(), outputArgument);
        const AString extension = LowerPathExtension<AString>(outputBase);
        if(extension.empty())
            outOutputPaths.metadata = outputBase;
        else if(extension == __hidden_output::s_NwbOutputExtension)
            outOutputPaths.metadata = outputBase;
        else{
            NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: --output must be an output base name or a .nwb filename."));
            return false;
        }
        outOutputPaths.metadata.replaceExtension(__hidden_output::s_NwbOutputExtension);
    }

    outOutputPaths.data = outOutputPaths.metadata;
    outOutputPaths.data.replaceExtension(TextureFormat::s_TextureDataExtension);
    outOutputPaths.metadataTemporary = outOutputPaths.metadata;
    outOutputPaths.metadataTemporary += s_TemporaryOutputSuffix;
    outOutputPaths.dataTemporary = outOutputPaths.data;
    outOutputPaths.dataTemporary += s_TemporaryOutputSuffix;
    return true;
}

bool ValidateOutputPaths(const OutputPaths& outputPaths, const bool force){
    Path dataBackup(outputPaths.data);
    Path metadataBackup(outputPaths.metadata);
    dataBackup += ".old";
    metadataBackup += ".old";
    return
        __hidden_output::CheckOutputPath(outputPaths.metadata, force, false)
        && __hidden_output::CheckOutputPath(outputPaths.data, force, false)
        && __hidden_output::CheckOutputPath(outputPaths.metadataTemporary, false, true)
        && __hidden_output::CheckOutputPath(outputPaths.dataTemporary, false, true)
        && __hidden_output::CheckOutputPath(dataBackup, false, true)
        && __hidden_output::CheckOutputPath(metadataBackup, false, true)
    ;
}

bool WriteOutputs(const OutputPaths& outputPaths, const TexturePayload& payload, const bool force){
    const AString metadata = __hidden_output::BuildMetadata(payload, outputPaths.data);
    if(metadata.empty()){
        NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: cannot write an unsupported texture payload format."));
        return false;
    }
    if(payload.alphaBytes.size() > Limit<usize>::s_Max - payload.bytes.size()){
        NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: texture payload is too large to write."));
        return false;
    }
    if(!ValidateOutputPaths(outputPaths, force))
        return false;

    Path backups[] = { outputPaths.data, outputPaths.metadata };
    for(Path& backup : backups)
        backup += ".old";
    const Path* outputs[] = { &outputPaths.data, &outputPaths.metadata };
    const Path* temporaries[] = { &outputPaths.dataTemporary, &outputPaths.metadataTemporary };
    bool ownedTemporary[2u] = {};
    bool backedUp[2u] = {};
    bool published[2u] = {};
    ErrorCode removalErrors[2u];
    ErrorCode restorationErrors[2u];
    ErrorCode temporaryErrors[2u];

    // Cleanup never allocates or logs through the throwing logger while an unexpected exception unwinds.
    const auto rollback = [&]()noexcept{
        for(u32 index = 2u; index > 0u; --index){
            const u32 current = index - 1u;
            if(published[current]){
                if(!RemoveFile(*outputs[current], removalErrors[current]) && removalErrors[current])
                    __hidden_output::CaptureCleanupFailure(*outputs[current], removalErrors[current]);
            }
            if(backedUp[current] && !removalErrors[current]){
                if(!RenamePath(backups[current], *outputs[current], restorationErrors[current]))
                    __hidden_output::CaptureCleanupFailure(backups[current], restorationErrors[current]);
            }
            if(ownedTemporary[current]){
                if(!RemoveFile(*temporaries[current], temporaryErrors[current]) && temporaryErrors[current])
                    __hidden_output::CaptureCleanupFailure(*temporaries[current], temporaryErrors[current]);
            }
        }
    };
    ScopeExit restoreOnFailure(rollback);

    const auto publish = [&](){
        if(!__hidden_output::StageOutput(
            outputPaths.dataTemporary,
            payload.bytes.data(),
            payload.bytes.size(),
            payload.alphaBytes.data(),
            payload.alphaBytes.size(),
            ownedTemporary[0u]
        )){
            NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: failed to stage output data file '{}'"), PathToString<tchar>(outputPaths.dataTemporary));
            return false;
        }
        if(!__hidden_output::StageOutput(
            outputPaths.metadataTemporary,
            metadata.data(),
            metadata.size(),
            nullptr,
            0u,
            ownedTemporary[1u]
        )){
            NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: failed to stage output metadata file '{}'"), PathToString<tchar>(outputPaths.metadataTemporary));
            return false;
        }

        for(u32 index = 0u; index < 2u; ++index){
            ErrorCode error;
            const bool present = FileExistsNoFollow(*outputs[index], error);
            if(error){
                NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: failed to inspect existing output '{}'"), PathToString<tchar>(*outputs[index]));
                return false;
            }
            if(!present)
                continue;
            if(!__hidden_output::CheckOutputPath(*outputs[index], force, false))
                return false;
            if(!__hidden_output::CheckOutputPath(backups[index], false, true))
                return false;
            if(!RenamePath(*outputs[index], backups[index], error)){
                NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: failed to preserve existing output '{}': {}")
                    , PathToString<tchar>(*outputs[index])
                    , StringConvert(error.message())
                );
                return false;
            }
            backedUp[index] = true;
        }
        for(u32 index = 0u; index < 2u; ++index){
            ErrorCode error;
            if(!RenamePath(*temporaries[index], *outputs[index], error)){
                NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: failed to finalize output '{}': {}")
                    , PathToString<tchar>(*outputs[index])
                    , StringConvert(error.message())
                );
                return false;
            }
            published[index] = true;
            ownedTemporary[index] = false;
        }
        return true;
    };
    if(!publish()){
        rollback();
        restoreOnFailure.release();
        for(u32 index = 0u; index < 2u; ++index){
            if(backedUp[index] && (removalErrors[index] || restorationErrors[index])){
                NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: failed to restore '{}'; previous output retained at '{}' (remove {}, restore {})")
                    , PathToString<tchar>(*outputs[index])
                    , PathToString<tchar>(backups[index])
                    , removalErrors[index].value()
                    , restorationErrors[index].value()
                );
            }
            if(!backedUp[index] && removalErrors[index]){
                NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: failed to remove newly published output '{}': {}")
                    , PathToString<tchar>(*outputs[index])
                    , StringConvert(removalErrors[index].message())
                );
            }
            if(temporaryErrors[index]){
                NWB_LOGGER_CRITICAL_WARNING(NWB_TEXT("tex_conv: failed to remove unpublished temporary '{}': {}")
                    , PathToString<tchar>(*temporaries[index])
                    , StringConvert(temporaryErrors[index].message())
                );
            }
        }
        return false;
    }

    restoreOnFailure.release();
    for(u32 index = 0u; index < 2u; ++index){
        if(!backedUp[index])
            continue;
        ErrorCode error;
        if(!RemoveFile(backups[index], error) && error){
            NWB_LOGGER_CRITICAL_WARNING(NWB_TEXT("tex_conv: published output pair but could not remove previous backup '{}': {}")
                , PathToString<tchar>(backups[index])
                , StringConvert(error.message())
            );
        }
    }
    return true;
}


