b8 ContextMenuState::open(const Rect& anchor)noexcept{
    if(!IsValidUiRect(anchor))
        return false;
    m_popup.close();
    m_popup.open();
    m_list.select(0u);
    if(!m_list.scrollTo(0.0))
        TerminateInvariant();
    m_anchor = anchor;
    advanceRevision();
    return true;
}

void ContextMenuState::close()noexcept{
    m_popup.close();
    m_list.select(0u);
    advanceRevision();
}

void ContextMenuState::advanceRevision()noexcept{
    if(m_revision == Limit<u64>::s_Max)
        TerminateInvariant();
    ++m_revision;
}


