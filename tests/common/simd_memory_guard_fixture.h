#if defined(NWB_PLATFORM_WINDOWS) || defined(NWB_PLATFORM_LINUX)
struct GuardedBytes final : NoCopy{
    void* mapping = nullptr;
    u8* data = nullptr;
    u8* lowerGuard = nullptr;
    u8* upperGuard = nullptr;
    usize pageBytes = 0u;
    usize accessibleBytes = 0u;
    usize mappingBytes = 0u;


public:
    GuardedBytes()noexcept;
    ~GuardedBytes()noexcept;
};
#endif


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


[[nodiscard]] constexpr u8 PatternByte(const usize index)noexcept{
    return static_cast<u8>((index * 37u + (index >> 8u) * 13u + 11u) & 0xFFu);
}

#if defined(NWB_PLATFORM_WINDOWS) || defined(NWB_PLATFORM_LINUX)
[[nodiscard]] inline u8* GuardAddress(const void* base, const usize byteOffset)noexcept{
    return reinterpret_cast<u8*>(reinterpret_cast<usize>(base) + byteOffset);
}

inline void ExitOnAbort([[maybe_unused]] const int signalNumber)noexcept{
    _exit(s_SIMDMemoryAbortExitCode);
}
#endif


