bool ResolveOutputPaths(const Path& inputPath, const AString& outputArgument, OutputPaths& outOutputPaths){
    if(outputArgument.empty()){
        outOutputPaths.metadata = inputPath;
        outOutputPaths.metadata.replace_extension(".nwb");
    }
    else{
        const Path outputBase(UtilityDetail::Arena(), outputArgument);
        const AString extension = ToAsciiLowerCopy(PathToGenericString<AString>(outputBase.extension()));
        if(extension.empty())
            outOutputPaths.metadata = outputBase;
        else if(extension == ".nwb")
            outOutputPaths.metadata = outputBase;
        else{
            NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: --output must be an output base name or a .nwb filename."));
            return false;
        }
        outOutputPaths.metadata.replace_extension(".nwb");
    }

    outOutputPaths.data = outOutputPaths.metadata;
    outOutputPaths.data.replace_extension(".tex");
    outOutputPaths.metadataTemporary = outOutputPaths.metadata;
    outOutputPaths.metadataTemporary += ".tmp";
    outOutputPaths.dataTemporary = outOutputPaths.data;
    outOutputPaths.dataTemporary += ".tmp";
    return true;
}

bool ValidateOutputPaths(const OutputPaths& outputPaths, const bool force){
    return __hidden_output::CheckOutputPath(outputPaths.metadata, force, false)
        && __hidden_output::CheckOutputPath(outputPaths.data, force, false)
        && __hidden_output::CheckOutputPath(outputPaths.metadataTemporary, false, true)
        && __hidden_output::CheckOutputPath(outputPaths.dataTemporary, false, true)
    ;
}

bool WriteOutputs(const OutputPaths& outputPaths, const TexturePayload& payload, const bool force){
    const AString metadata = __hidden_output::BuildMetadata(payload, outputPaths.data);
    if(metadata.empty()){
        NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: cannot write an unsupported texture payload format."));
        return false;
    }
    if(payload.alphaBytes.size() > Limit<usize>::s_Max - payload.bytes.size()){
        NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: texture payload is too large to write."));
        return false;
    }
    if(!__hidden_output::WriteTexturePayload(outputPaths.dataTemporary, payload)){
        NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: failed to write output data file '{}'.")
            , PathToString<tchar>(outputPaths.dataTemporary)
        );
        __hidden_output::RemoveTemporaryFile(outputPaths.dataTemporary);
        return false;
    }
    if(!WriteTextFile(outputPaths.metadataTemporary, metadata)){
        NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: failed to write output metadata file '{}'.")
            , PathToString<tchar>(outputPaths.metadataTemporary)
        );
        __hidden_output::RemoveTemporaryFile(outputPaths.dataTemporary);
        __hidden_output::RemoveTemporaryFile(outputPaths.metadataTemporary);
        return false;
    }

    if(force){
        if(!__hidden_output::RemoveOutputPath(outputPaths.data) || !__hidden_output::RemoveOutputPath(outputPaths.metadata)){
            __hidden_output::RemoveTemporaryFile(outputPaths.dataTemporary);
            __hidden_output::RemoveTemporaryFile(outputPaths.metadataTemporary);
            return false;
        }
    }

    ErrorCode errorCode;
    if(!RenamePath(outputPaths.dataTemporary, outputPaths.data, errorCode)){
        NWB_LOGGER_ERROR(
            NWB_TEXT("tex_conv: failed to finalize output data file '{}': {}")
            , PathToString<tchar>(outputPaths.data)
            , StringConvert(errorCode.message())
        );
        __hidden_output::RemoveTemporaryFile(outputPaths.dataTemporary);
        __hidden_output::RemoveTemporaryFile(outputPaths.metadataTemporary);
        return false;
    }
    if(!RenamePath(outputPaths.metadataTemporary, outputPaths.metadata, errorCode)){
        NWB_LOGGER_ERROR(
            NWB_TEXT("tex_conv: failed to finalize output metadata file '{}': {}")
            , PathToString<tchar>(outputPaths.metadata)
            , StringConvert(errorCode.message())
        );
        __hidden_output::RemoveTemporaryFile(outputPaths.data);
        __hidden_output::RemoveTemporaryFile(outputPaths.metadataTemporary);
        return false;
    }

    return true;
}


