namespace __hidden_gather_merge_registry{


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


::AutoRegistrationQueue<AssetGatherMergeFunction, AssetArena>& QueryAutoMergeQueue(){
    static ::AutoRegistrationQueue<AssetGatherMergeFunction, AssetArena> queue(
        AssetsArenaScope::s_GatherMergeQueueArena
    );
    return queue;
}


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


AssetGatherMergeAutoRegistrar::AssetGatherMergeAutoRegistrar(const AssetGatherMergeFunction function){
    ::RegisterAutoFactory(__hidden_gather_merge_registry::QueryAutoMergeQueue(), function);
}

AssetGatherMergeFunction QueryAutoCollectedAssetGatherMerge(){
    Core::Alloc::ScratchArena scratchArena(AssetsArenaScope::s_GatherMergeQueryScratch);
    Vector<AssetGatherMergeFunction, Core::Alloc::ScratchArena> functions{scratchArena};
    __hidden_gather_merge_registry::QueryAutoMergeQueue().copyTo(functions);

    for(const AssetGatherMergeFunction function : functions){
        NWB_ASSERT(function != nullptr);
        return function;
    }
    return nullptr;
}


