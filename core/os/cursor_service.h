class TrackedCursorService : public ICursorService{
public:
    explicit TrackedCursorService(Alloc::GlobalArena& arena)noexcept;
    virtual ~TrackedCursorService()noexcept override;


public:
    [[nodiscard]] virtual b8 isOwnerThread()const noexcept override final{ return QueryCurrentThreadId() == m_ownerThread; }
    [[nodiscard]] virtual b8 setCursor(CursorShape::Enum shape)noexcept override final;
    [[nodiscard]] virtual CursorShape::Enum currentCursor()const noexcept override final{ return m_currentShape; }


protected:
    [[nodiscard]] virtual b8 applyNativeCursor(CursorShape::Enum shape)noexcept;


private:
    const ThreadId m_ownerThread;
    CursorShape::Enum m_currentShape = CursorShape::Default;
    b8 m_applied = false;
};


