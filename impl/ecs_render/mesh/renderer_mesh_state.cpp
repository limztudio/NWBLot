RendererMeshState::RendererMeshState(Core::Alloc::GlobalArena& arena)
    : m_meshes(0, Hasher<Name>(), EqualTo<Name>(), arena)
{}


void RendererMeshState::invalidateResources(){
    m_meshes.clear();
    m_meshViewBuffer.reset();
    m_frameBindings = {};
    m_meshViewGpuDataValid = false;
}


