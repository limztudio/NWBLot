static bool ParseFontAtlasDocument(
    const Path& assetRoot,
    const AStringView virtualRoot,
    const Path& nwbFilePath,
    const Core::Metascript::Document& doc,
    FontAtlasCookEntry& outEntry,
    Core::Assets::CookEntryParseContext& context){
    return ParseFontAtlasCookMetadata(assetRoot, virtualRoot, nwbFilePath, doc, outEntry, context.scratchArena);
}

static bool RegisterFontAtlasCookEntry(Core::Assets::CookEntryRegistry& registry){
    return
        Core::Assets::RegisterSingleDocumentCookEntry<FontAtlasCookEntry, FontAtlas, FontAtlasAssetCodec>(
            registry,
            MakeNotNull(NWB_TEXT("font atlas")),
            &ParseFontAtlasDocument,
            [](FontAtlasCookEntry& entry, FontAtlas& outAsset){ return Core::Assets::ForwardCookBuild(entry, outAsset, &BuildFontAtlasAsset); },
            false
        )
    ;
}


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


NWB_DEFINE_COOK_ENTRY_REGISTRAR(s_FontAtlasCookEntryRegistrar, RegisterFontAtlasCookEntry);


