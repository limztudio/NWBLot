void CsgDeformCapBuilder::CollectBoundaryEdges(Core::Alloc::ScratchArena&, const Span<const CsgDeformTriangle> triangles, Vector<CsgDeformCutLoopEdge, Core::Alloc::ScratchArena>& outEdges){
    CollectCsgDeformBoundaryEdges(triangles, outEdges);
}

b8 CsgDeformCapBuilder::OrderBoundaryLoop(Core::Alloc::ScratchArena&, const Span<const CsgDeformCutLoopEdge> edges, Vector<u32, Core::Alloc::ScratchArena>& outLoop){
    return OrderCsgDeformBoundaryLoop(edges, outLoop);
}

Expected<u32> CsgDeformCapBuilder::FillCutCaps(
    Core::Alloc::ScratchArena&,
    Vector<CsgDeformCutLoopEdge, Core::Alloc::ScratchArena>& scratchEdges,
    CsgDeformVertexVector<Core::Alloc::ScratchArena>& inOutVertices,
    CsgDeformTriangleVector<Core::Alloc::ScratchArena>& inOutTriangles
){
    return FillCsgDeformCutCaps(scratchEdges, inOutVertices, inOutTriangles);
}


