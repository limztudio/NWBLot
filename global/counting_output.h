struct CountingByteOutput{
    usize byteCount = 0u;


public:
    constexpr CountingByteOutput& operator*()noexcept{ return *this; }

    constexpr CountingByteOutput& operator++(int)noexcept{ return *this; }

    constexpr CountingByteOutput& operator=(const char){
        byteCount = AddSize(byteCount, 1u);
        return *this;
    }
};


