#if !defined(NWB_COOK)
b8 IAsset::checkVirtualPath(const TStringView failureContext)const{
    if(virtualPath())
        return true;

    NWB_LOGGER_ERROR(FOUNDATION_TEXT("{} failed: virtual path is empty"), failureContext);
    return false;
}
#else
b8 IAssetCodec::checkSerializeAssetType(const IAsset& asset, const TStringView failureContext)const{
    if(asset.assetType() == assetType())
        return true;

    NWB_LOGGER_ERROR(FOUNDATION_TEXT("{} failed: invalid asset type '{}', expected '{}'"), failureContext, ConvertString(asset.assetType().resolvedText()), ConvertString(assetType().resolvedText()));
    return false;
}
#endif


