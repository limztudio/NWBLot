TEST(AssetsGraphics, FixtureCaseRootIsIsolatedPerCase){
    TestArena firstArena;
    TestArena secondArena;
    const AssetsGraphicsFixture::Path firstRoot = AssetsGraphicsFixture::AssetsGraphicsTestCaseRoot(firstArena, "suite_smoke_first");
    const AssetsGraphicsFixture::Path secondRoot = AssetsGraphicsFixture::AssetsGraphicsTestCaseRoot(secondArena, "suite_smoke_second");
    EXPECT_NE(firstRoot, secondRoot);
    EXPECT_TRUE(AssetsGraphicsFixture::PrepareCleanDirectory(firstRoot));
    EXPECT_TRUE(AssetsGraphicsFixture::PrepareCleanDirectory(secondRoot));
    ErrorCode errorCode;
    EXPECT_TRUE(RemoveAllIfExists(firstRoot, errorCode));
    EXPECT_TRUE(RemoveAllIfExists(secondRoot, errorCode));
}


