template<typename UsageFlags, typename CreateFlags>
struct NativeResourceProvenance{
    const u32* queueFamilyIndices = nullptr;
    UsageFlags usage = 0u;
    CreateFlags flags = 0u;
    VkSharingMode sharingMode = VK_SHARING_MODE_EXCLUSIVE;
    u32 queueFamilyIndexCount = 0u;
    b8 initialStateKnown = true;
};


using NativeBufferProvenance = NativeResourceProvenance<VkBufferUsageFlags, VkBufferCreateFlags>;
using NativeTextureProvenance = NativeResourceProvenance<VkImageUsageFlags, VkImageCreateFlags>;


