// Opaque compute-emulation merge validation owns packet-merge checks for prefix tasks.
struct OpaqueEmulationMergeValidationResult{
    bool packetsAreGraphics = false;
    bool opaqueComputeEmulationMerged = false;
    bool opaqueSharedComputeEmulationMerged = false;
    bool opaqueCsgReceiverComputeEmulationMerged = false;
    bool opaqueCsgIntervalSampleComputeEmulationMerged = false;
    bool csgIntervalClearBundleMerged = false;
};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


class OpaqueEmulationMergeValidator final : NoCopy{
public:
    explicit OpaqueEmulationMergeValidator(NotNull<RendererFramePipeline*> pipeline);


public:
    void validate(
        const Core::GpuCompiledGraph::ReadView& compiledPlan,
        const Core::GpuTaskId* timingTasks,
        usize timingTaskCount,
        bool timingBindingsValid,
        bool hasOpaqueCsgFrameWork,
        OpaqueEmulationMergeValidationResult& outResult
    )const;


private:
    NotNull<RendererFramePipeline*> m_pipeline;
};


