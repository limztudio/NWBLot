// Unavailable or unstamped inputs disable temporal reuse; versions alone prove nothing.
struct ReflectionSceneContentStamp{
    u64 geometry = 0u;
    u64 material = 0u;
    u64 lighting = 0u;
    u64 view = 0u;
    bool trusted = false;


public:
    [[nodiscard]] constexpr bool matchesScene(const ReflectionSceneContentStamp& other)const noexcept{
        return geometry == other.geometry && material == other.material && lighting == other.lighting && trusted == other.trusted;
    }
};


