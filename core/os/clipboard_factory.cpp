namespace __hidden_clipboard_factory{


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


class UnsupportedClipboardService final : public QueuedClipboardService{
public:
    using QueuedClipboardService::QueuedClipboardService;


public:
    [[nodiscard]] virtual ClipboardCapabilities capabilities(ClipboardChannel::Enum)const noexcept override{ return {}; }


protected:
    [[nodiscard]] virtual ClipboardStatus::Enum readNativeText(ClipboardChannel::Enum, AString<Alloc::GlobalArena>&)override{
        return ClipboardStatus::Unsupported;
    }

    [[nodiscard]] virtual ClipboardStatus::Enum writeNativeText(ClipboardChannel::Enum, AStringView)override{
        return ClipboardStatus::Unsupported;
    }
};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


GlobalUniquePtr<IClipboardService> CreateClipboardService(Alloc::GlobalArena& arena, void* const nativeWindowHandle){
#if defined(NWB_PLATFORM_WINDOWS)
    if(nativeWindowHandle)
        return MakeGlobalUnique<Win32ClipboardService>(arena, arena, MakeNotNull(nativeWindowHandle));
#else
    static_cast<void>(nativeWindowHandle);
#endif
    return MakeGlobalUnique<__hidden_clipboard_factory::UnsupportedClipboardService>(arena, arena);
}


