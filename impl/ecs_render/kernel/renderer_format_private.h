template<usize N>
inline Core::Format::Enum SelectSupportedFormat(Core::Device& device, const Core::Format::Enum (&candidates)[N], const Core::FormatSupport::Mask requiredSupport){
    for(const Core::Format::Enum format : candidates){
        if((device.queryFormatSupport(format) & requiredSupport) == requiredSupport)
            return format;
    }

    return Core::Format::UNKNOWN;
}

inline bool CreateClampSampler(Core::Device& device, Core::SamplerHandle& sampler, const bool linearFiltering){
    if(sampler)
        return true;

    Core::SamplerDesc samplerDesc;
    samplerDesc.setAllFilters(linearFiltering).setAllAddressModes(Core::SamplerAddressMode::Clamp);
    auto samplerResult = device.createSampler(samplerDesc);
    if(samplerResult)
        sampler = Move(*samplerResult);
    else
        sampler.reset();
    if(samplerResult)
        return true;

    return false;
}


