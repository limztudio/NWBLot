TEST(GpuCrashMarkerTracker, ResetEventStackPreservesHistoryAndClearsNesting){
    TestArena testArena;
    Core::GpuCrashMarkerTracker tracker(testArena.arena);

    const usize outerHash = tracker.pushEvent("Outer");
    const usize nestedHash = tracker.pushEvent("Inner");
    const Core::ResolvedMarker nested = tracker.getEventString(nestedHash);
    ASSERT_TRUE(nested.first());
    EXPECT_EQ(nested.second(), AStringView("Outer/Inner"));

    tracker.resetEventStack();

    const usize freshHash = tracker.pushEvent("Fresh");
    const Core::ResolvedMarker fresh = tracker.getEventString(freshHash);
    ASSERT_TRUE(fresh.first());
    EXPECT_EQ(fresh.second(), AStringView("Fresh"));

    const Core::ResolvedMarker historicalOuter = tracker.getEventString(outerHash);
    const Core::ResolvedMarker historicalNested = tracker.getEventString(nestedHash);
    ASSERT_TRUE(historicalOuter.first());
    ASSERT_TRUE(historicalNested.first());
    EXPECT_EQ(historicalOuter.second(), AStringView("Outer"));
    EXPECT_EQ(historicalNested.second(), AStringView("Outer/Inner"));

    tracker.popEvent();
    tracker.popEvent();
    const usize finalHash = tracker.pushEvent("Final");
    const Core::ResolvedMarker final = tracker.getEventString(finalHash);
    ASSERT_TRUE(final.first());
    EXPECT_EQ(final.second(), AStringView("Final"));
}


