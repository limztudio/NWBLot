struct SamplerGpuResource final : NoCopy{
    Core::SamplerHandle sampler;
    Core::GpuDescriptorHandle samplerHeapHandle = Core::GpuDescriptorHandle::invalid();

    [[nodiscard]] bool valid()const{
        return sampler != nullptr && samplerHeapHandle.valid();
    }
};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


namespace SamplerAssetLoader{


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


[[nodiscard]] bool Create(
    SamplerGpuResource& outResource,
    const Sampler& samplerAsset,
    const Name& debugName,
    Core::Graphics& graphics,
    const tchar* ownerName
);
[[nodiscard]] bool Load(
    SamplerGpuResource& outResource,
    const Name& samplerVirtualPath,
    const Name& debugName,
    Core::Graphics& graphics,
    Core::Assets::AssetManager& assetManager,
    const tchar* ownerName
);
void Release(SamplerGpuResource& inOutResource, Core::Graphics& graphics);


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


};


