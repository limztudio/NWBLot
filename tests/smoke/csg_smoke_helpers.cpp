void AssignCsgCutterTransform(const SIMDVectorSingle center, const SIMDVectorSingle rotation, Impl::CsgCutterComponent& cutter)noexcept{
    const SIMDMatrix shapeToWorld = MatrixAffineTransformation(s_SIMDOne, VectorZero(), rotation, center);
    SIMDVectorSingle determinant;
    const SIMDMatrix worldToShape = MatrixInverse(&determinant, shapeToWorld);
    StoreFloat(worldToShape, cutter.worldToShape);
    StoreFloat(shapeToWorld, cutter.shapeToWorld);
}

Impl::StaticCsgMeshComponent& AddStaticCsgMeshReceiver(const Core::ECS::EntityID entity, const Name receiverGroup, const b8 affectOpaquePass, const b8 affectTransparentPass, Core::ECS::World& world){
    return AddCsgMeshReceiver<Impl::StaticCsgMeshComponent>(entity, receiverGroup, affectOpaquePass, affectTransparentPass, world);
}

Impl::SkinnedCsgMeshComponent& AddSkinnedCsgMeshReceiver(const Core::ECS::EntityID entity, const Name receiverGroup, const b8 affectOpaquePass, const b8 affectTransparentPass, Core::ECS::World& world){
    return AddCsgMeshReceiver<Impl::SkinnedCsgMeshComponent>(entity, receiverGroup, affectOpaquePass, affectTransparentPass, world);
}


