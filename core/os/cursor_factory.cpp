namespace __hidden_cursor_factory{


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


class UnsupportedCursorService final : public TrackedCursorService{
public:
    using TrackedCursorService::TrackedCursorService;


public:
    [[nodiscard]] virtual CursorCapabilities capabilities()const noexcept override{ return {}; }
};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


Expected<GlobalUniquePtr<ICursorService>> CreateCursorService(Alloc::GlobalArena& arena, [[maybe_unused]] void* const nativeWindowHandle){
#if defined(FOUNDATION_PLATFORM_WINDOWS)
    if(nativeWindowHandle){
        auto service = MakeGlobalUnique<Win32CursorService>(arena, arena, MakeNotNull(nativeWindowHandle));
        if(!service)
            return MakeUnexpected(Failure{});
        return service;
    }
#endif
    auto service = MakeGlobalUnique<__hidden_cursor_factory::UnsupportedCursorService>(arena, arena);
    if(!service)
        return MakeUnexpected(Failure{});
    return service;
}


