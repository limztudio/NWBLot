struct UnicodePropertyRange{
    u32 first;
    u32 last;
    u8 property;
};

template<usize Count>
[[nodiscard]] u8 LookupUnicodePropertyRanges(const UnicodePropertyRange (&ranges)[Count], const u32 scalar, const u8 fallback){
    usize first = 0u;
    usize last = Count;
    while(first < last){
        const usize middle = first + (last - first) / 2u;
        if(scalar < ranges[middle].first)
            last = middle;
        else if(scalar > ranges[middle].last)
            first = middle + 1u;
        else
            return ranges[middle].property;
    }
    return fallback;
}


