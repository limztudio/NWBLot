static Expected<SkeletonCookEntry> ParseSkeletonDocument(
    const Path& assetRoot,
    const AStringView virtualRoot,
    const Path& nwbFilePath,
    const Core::Metascript::Document& doc,
    Core::Assets::CookEntryParseContext& context
){
    return ParseSkeletonCookMetadata(
        assetRoot,
        virtualRoot,
        nwbFilePath,
        doc,
        context.cookArena,
        context.scratchArena
    );
}

static Expected<SkeletonCookEntry> ParseSkeletonValue(
    const Name virtualPath,
    const Path& nwbFilePath,
    const Core::Metascript::Value& asset,
    Core::Assets::CookEntryParseContext& context
){
    return ParseSkeletonCookMetadata(
        virtualPath,
        nwbFilePath,
        asset,
        context.cookArena
    );
}

static bool RegisterSkeletonCookEntry(Core::Assets::CookEntryRegistry& registry){
    return Core::Assets::RegisterDocumentValueCookEntry<SkeletonCookEntry, Skeleton, SkeletonAssetCodec>(
        registry,
        NWB_TEXT("skeleton"),
        &ParseSkeletonDocument,
        &ParseSkeletonValue,
        [](SkeletonCookEntry& entry, Core::Assets::AssetArena& arena){ return Core::Assets::ForwardCookBuild(entry, arena, &BuildSkeletonAsset); }
    );
}


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


NWB_DEFINE_COOK_ENTRY_REGISTRAR(s_SkeletonCookEntryRegistrar, RegisterSkeletonCookEntry);


