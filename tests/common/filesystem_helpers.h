template<typename ArenaT>
[[nodiscard]] inline bool TextFileContains(const ::Path<ArenaT>& path, const AStringView needle){
    AString<ArenaT> text(path.arena());
    if(!ReadTextFile(path, text))
        return false;

    return AStringView(text.data(), text.size()).find(needle) != AStringView::npos;
}

template<typename ArenaT>
[[nodiscard]] inline Expected<bool, ErrorCode> WaitForDirectory(const ::Path<ArenaT>& path, const u32 timeoutMilliseconds, const u32 pollMilliseconds = FilesystemTestDetail::s_DefaultDirectoryPollMilliseconds){
    const u32 stepMilliseconds = pollMilliseconds == 0u ? FilesystemTestDetail::s_MinimumDirectoryPollMilliseconds : pollMilliseconds;
    const Timer deadline = TimerAddMS(TimerNow(), timeoutMilliseconds);
    for(;;){
        const auto directory = IsDirectory(path);
        if(!directory)
            return MakeUnexpected(directory.error());
        if(*directory)
            return true;
        const Timer now = TimerNow();
        if(now >= deadline)
            return false;
        const u32 remainingMilliseconds = static_cast<u32>(Max(DurationInMS<i64>(deadline, now), i64(FilesystemTestDetail::s_MinimumDirectoryPollMilliseconds)));
        SleepMS(Min(stepMilliseconds, remainingMilliseconds));
    }
}


