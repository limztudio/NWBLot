struct SliderOptions;
struct SliderStyle;

struct SliderMetrics{
    Insets padding;
    Point thumbExtent = { 24.0f, 24.0f };
    f32 trackHeight = 12.0f;
    Point contentSize;
};

struct SliderPlacement{
    Rect bounds;
    Rect clip;
    Rect travelBounds;
    Rect track;
    Rect centerTravel;
    Rect thumb;
    Point thumbExtent;
};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


class SliderLayout final{
public:
    // Invalid metrics or prospective rectangles preserve the previous output.
    [[nodiscard]] static bool Measure(const SliderOptions& options, const SliderStyle& style, SliderMetrics& out)noexcept;
    [[nodiscard]] static bool Place(
        const Rect& bounds,
        const Rect& clip,
        const SliderMetrics& metrics,
        f64 normalized,
        SliderPlacement& out
    )noexcept;
};


