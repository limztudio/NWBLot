static Expected<TextureCookEntry> ParseTextureDocument(
    const Path& assetRoot,
    const AStringView virtualRoot,
    const Path& nwbFilePath,
    const Core::Metascript::Document& doc,
    Core::Assets::CookEntryParseContext& context
){
    return ParseTextureCookMetadata(
        assetRoot,
        virtualRoot,
        nwbFilePath,
        doc,
        context.cookArena,
        context.scratchArena
    );
}

static bool RegisterTextureCookEntry(Core::Assets::CookEntryRegistry& registry){
    return Core::Assets::RegisterSingleDocumentCookEntry<TextureCookEntry, Texture, TextureAssetCodec>(
        registry,
        TextureBinaryPayload::s_TextureAssetKindLabel,
        &ParseTextureDocument,
        [](TextureCookEntry& entry, Core::Assets::AssetArena& arena){ return Core::Assets::ForwardCookBuild(entry, arena, &BuildTextureAsset); },
        false
    );
}


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


NWB_DEFINE_COOK_ENTRY_REGISTRAR(s_TextureCookEntryRegistrar, RegisterTextureCookEntry);


