namespace ECSRenderDetail{


// Generated geometry stores compact vertices and indices in one allocation; legacy draws use only its vertex region.
inline constexpr Core::ResourceStates::Mask s_GeneratedGeometryRasterState =
    Core::ResourceStates::VertexBuffer | Core::ResourceStates::IndexBuffer;


// Buffer identity alone does not describe which regions a retained draw generates and consumes.
struct GeneratedGeometryOutputLayout{
    u32 m_indexByteOffset = 0u;
    bool m_indexed = false;

    [[nodiscard]] constexpr bool matches(const u32 indexByteOffset, const bool indexed)const noexcept{
        return m_indexByteOffset == indexByteOffset && m_indexed == indexed;
    }
};


};


