namespace __hidden_clipboard_factory{


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


class UnsupportedClipboardService final : public QueuedClipboardService{
public:
    using QueuedClipboardService::QueuedClipboardService;


public:
    [[nodiscard]] virtual ClipboardCapabilities capabilities(ClipboardChannel::Enum)const noexcept override{ return {}; }


protected:
    virtual void startNativeRequest(const ClipboardRequestToken token, const ClipboardOperation::Enum, const ClipboardChannel::Enum, const AStringView)override{
        if(!completeNativeRequest(token, ClipboardStatus::Unsupported))
            NWB_FATAL_ASSERT(false);
    }
};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


Expected<GlobalUniquePtr<IClipboardService>> CreateClipboardService(Alloc::GlobalArena& arena, void* const nativeWindowHandle){
#if defined(NWB_PLATFORM_WINDOWS)
    if(nativeWindowHandle){
        auto service = MakeGlobalUnique<Win32ClipboardService>(arena, arena, MakeNotNull(nativeWindowHandle));
        if(!service)
            return MakeUnexpected(Failure{});
        return service;
    }
#else
    static_cast<void>(nativeWindowHandle);
#endif
    auto service = MakeGlobalUnique<__hidden_clipboard_factory::UnsupportedClipboardService>(arena, arena);
    if(!service)
        return MakeUnexpected(Failure{});
    return service;
}


