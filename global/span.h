#pragma once


#include "type.h"

#include <span>


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


inline constexpr usize s_DynamicExtent = std::dynamic_extent;

template<typename T, usize Extent = s_DynamicExtent>
using Span = std::span<T, Extent>;


template<typename T, usize Extent>
[[nodiscard]] constexpr b8 HasSpanStorage(const Span<const T, Extent> values)noexcept{
    return values.data() != nullptr;
}


template<typename T>
[[nodiscard]] constexpr Span<const T> SpanOf(const T& value)noexcept{ return { &value, 1u }; }


