TrackedCursorService::TrackedCursorService([[maybe_unused]] Alloc::GlobalArena& arena)noexcept
    : m_ownerThread(QueryCurrentThreadId())
{}

TrackedCursorService::~TrackedCursorService()noexcept{
    FOUNDATION_ASSERT(isOwnerThread());
}

b8 TrackedCursorService::setCursor(const CursorShape::Enum shape)noexcept{
    if(!isOwnerThread())
        return false;
    if(static_cast<u8>(shape) >= static_cast<u8>(CursorShape::kCount))
        return false;
    if(m_applied && m_currentShape == shape)
        return true;
    if(!applyNativeCursor(shape))
        return false;
    m_currentShape = shape;
    m_applied = true;
    return true;
}

b8 TrackedCursorService::applyNativeCursor([[maybe_unused]] const CursorShape::Enum shape)noexcept{
    return true;
}


