static_assert(sizeof(Core::Object) == sizeof(u64));
static_assert(alignof(Core::Object) == alignof(u64));
static_assert(IsStandardLayout_V<Core::Object>);
static_assert(IsTriviallyCopyable_V<Core::Object>);


TEST(GraphicsNativeObject, PointerAndIntegerConstructionShareCanonicalBits){
    u32 storage = 0x1a2b3c4du;
    void* const pointer = &storage;
    const u64 expectedBits = static_cast<u64>(reinterpret_cast<usize>(pointer));

    const Core::Object pointerObject(pointer);
    const Core::Object integerObject(expectedBits);

    EXPECT_EQ(pointerObject.integer, expectedBits);
    EXPECT_EQ(pointerObject.pointer(), pointer);
    EXPECT_EQ(static_cast<u32*>(pointerObject), &storage);
    EXPECT_EQ(integerObject.pointer(), pointer);
    EXPECT_EQ(pointerObject, integerObject);
    EXPECT_FALSE(pointerObject != integerObject);
}

TEST(GraphicsNativeObject, NullPointerUsesZeroIdentity){
    const Core::Object pointerObject(nullptr);
    constexpr Core::Object integerObject(u64{0u});

    EXPECT_EQ(pointerObject.integer, 0u);
    EXPECT_EQ(pointerObject.pointer(), nullptr);
    EXPECT_EQ(static_cast<void*>(pointerObject), nullptr);
    EXPECT_EQ(pointerObject, integerObject);
}


