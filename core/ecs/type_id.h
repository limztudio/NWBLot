////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


using ComponentTypeId = usize;
using SystemTypeId = usize;
using MessageTypeId = usize;


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


namespace ECSDetail{


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


struct ComponentTypeTag{};
struct SystemTypeTag{};
struct MessageTypeTag{};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


template<typename T>
inline ComponentTypeId ComponentType()noexcept{
    return ::TypeCounter<ECSDetail::ComponentTypeTag>::Id<Decay_T<T>>();
}

template<typename T>
inline SystemTypeId SystemType()noexcept{
    return ::TypeCounter<ECSDetail::SystemTypeTag>::Id<Decay_T<T>>();
}

template<typename T>
inline MessageTypeId MessageType()noexcept{
    return ::TypeCounter<ECSDetail::MessageTypeTag>::Id<Decay_T<T>>();
}


