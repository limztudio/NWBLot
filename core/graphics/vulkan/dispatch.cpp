namespace __hidden_vulkan_dispatch{


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


Futex& GetVolkTableLoadMutex(){
    static Futex mutex;
    return mutex;
}


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


namespace VulkanDetail{


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


VkResult InitializeVolkLoader()noexcept{
    static const VkResult result = volkInitialize();
    return result;
}

void LoadVolkInstanceDispatch(VolkInstanceTable& instanceDispatch, const VkInstance instance)noexcept{
    NWB_ASSERT(instance != VK_NULL_HANDLE);
    ScopedLock lock(__hidden_vulkan_dispatch::GetVolkTableLoadMutex());

    volkLoadInstanceTable(&instanceDispatch, instance);
}

void LoadVolkDeviceDispatch(
    VolkInstanceTable& instanceDispatch,
    VolkDeviceTable& deviceDispatch,
    const VkInstance instance,
    const VkDevice device
)noexcept{
    NWB_ASSERT(instance != VK_NULL_HANDLE);
    NWB_ASSERT(device != VK_NULL_HANDLE);
    ScopedLock lock(__hidden_vulkan_dispatch::GetVolkTableLoadMutex());

    // Volk's table loader still obtains vkGetDeviceProcAddr through one process-global slot. Pair the owning
    // instance-table refresh and device-table load under one initialization lock, then use only the resulting tables.
    volkLoadInstanceTable(&instanceDispatch, instance);
    volkLoadDeviceTable(&deviceDispatch, device);
}


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


};


