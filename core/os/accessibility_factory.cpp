////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


namespace __hidden_accessibility_factory{


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


class UnsupportedAccessibilityService final : public TrackedAccessibilityService{
public:
    using TrackedAccessibilityService::TrackedAccessibilityService;


public:
    [[nodiscard]] virtual AccessibilityCapabilities capabilities()const noexcept override{ return {}; }
};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


Expected<GlobalUniquePtr<IAccessibilityService>> CreateAccessibilityService(Alloc::GlobalArena& arena, [[maybe_unused]] void* const nativeWindowHandle){
#if defined(FOUNDATION_PLATFORM_WINDOWS)
    if(nativeWindowHandle){
        auto service = MakeGlobalUnique<Win32AccessibilityService>(arena, arena, MakeNotNull(nativeWindowHandle));
        if(!service)
            return MakeUnexpected(Failure{});
        return service;
    }
#endif
    auto service = MakeGlobalUnique<__hidden_accessibility_factory::UnsupportedAccessibilityService>(arena, arena);
    if(!service)
        return MakeUnexpected(Failure{});
    return service;
}


