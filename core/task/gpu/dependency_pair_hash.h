[[nodiscard]] constexpr u64 PackGpuTaskDependencyPairKey(const u32 producerIndex, const u32 consumerIndex)noexcept{
    return PackU32Words(consumerIndex, producerIndex);
}

struct GpuTaskDependencyPairHasher{
    [[nodiscard]] usize operator()(u64 pairKey)const noexcept{
        pairKey ^= pairKey >> 30u;
        pairKey *= 0xBF58476D1CE4E5B9ull;
        pairKey ^= pairKey >> 27u;
        pairKey *= 0x94D049BB133111EBull;
        pairKey ^= pairKey >> 31u;
        return static_cast<usize>(pairKey);
    }
};


