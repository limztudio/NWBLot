static bool ParseFontDocument(
    const Path& assetRoot,
    const AStringView virtualRoot,
    const Path& nwbFilePath,
    const Core::Metascript::Document& doc,
    FontCookEntry& outEntry,
    Core::Assets::CookEntryParseContext& context){
    return ParseFontCookMetadata(assetRoot, virtualRoot, nwbFilePath, doc, outEntry, context.scratchArena);
}

static bool RegisterFontCookEntry(Core::Assets::CookEntryRegistry& registry){
    return Core::Assets::RegisterSingleDocumentCookEntry<FontCookEntry, Font, FontAssetCodec>(
        registry,
        MakeNotNull(NWB_TEXT("font")),
        &ParseFontDocument,
        [](FontCookEntry& entry, Font& outAsset){ return Core::Assets::ForwardCookBuild(entry, outAsset, &BuildFontAsset); },
        false
    );
}


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


NWB_DEFINE_COOK_ENTRY_REGISTRAR(s_FontCookEntryRegistrar, RegisterFontCookEntry);


