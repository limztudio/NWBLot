TrackedResourceStateHistory::TrackedResourceStateHistory(
    Vector<TrackedCompiledResourceState, Alloc::ScratchArena>& states,
    const usize resourceCount,
    const u64 graphGeneration,
    Alloc::ScratchArena& scratchArena)
    : m_states(states)
    , m_resources(resourceCount, scratchArena)
    , m_links(scratchArena)
    , m_graphGeneration(graphGeneration){
    m_links.reserve(states.capacity());
}


bool TrackedResourceStateHistory::append(const TrackedCompiledResourceState& state){
    if(!validFor(m_states) || !validResource(state.resource))
        return false;

    const usize stateIndex = m_states.size();
    ResourceLinks& resource = m_resources[state.resource.index];
    const usize previousIndex = resource.last;
    m_states.push_back(state);
    m_links.push_back(StateLinks{ .previous = previousIndex });
    if(previousIndex != Limit<usize>::s_Max)
        m_links[previousIndex].next = stateIndex;
    else
        resource.first = stateIndex;
    resource.last = stateIndex;
    return true;
}


