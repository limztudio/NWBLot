////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


using SignalAtomic = std::sig_atomic_t;
using SignalHandler = void (*)(i32);


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


namespace ProcessSignal{


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


enum Enum : i32{
    Interrupt = SIGINT,
    Terminate = SIGTERM,
};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


[[nodiscard]] inline u32 CurrentProcessId()noexcept{
#if defined(FOUNDATION_PLATFORM_WINDOWS)
    return static_cast<u32>(GetCurrentProcessId());
#elif defined(FOUNDATION_PLATFORM_LINUX) || defined(FOUNDATION_PLATFORM_ANDROID)
    return static_cast<u32>(getpid());
#else
    return 0u;
#endif
}

[[nodiscard]] inline b8 SetSignalHandler(ProcessSignal::Enum signalValue, SignalHandler handler)noexcept{
    return std::signal(signalValue, handler) != SIG_ERR;
}


