namespace __hidden_ui_radio_group_state{


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


[[nodiscard]] static u64 NextIdentity(){
    static Atomic<u64> s_NextIdentity{ 1u };
    const u64 identity = s_NextIdentity.fetch_add(1u, MemoryOrder::relaxed);
    if(identity == 0u || identity == Limit<u64>::s_Max)
        TerminateInvariant();
    return identity;
}


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


RadioGroupState::RadioGroupState()
    : m_instanceGeneration(__hidden_ui_radio_group_state::NextIdentity())
    , m_inputGeneration(__hidden_ui_radio_group_state::NextIdentity())
{}

RadioGroupSnapshot RadioGroupState::snapshot()const{
    return { m_instanceGeneration, m_inputGeneration, m_revision, m_selected, m_cursor, m_sourceGeneration, m_sourceRevision };
}

bool RadioGroupState::matches(const RadioGroupSnapshot& value)const{
    return snapshot() == value;
}

void RadioGroupState::select(const u64 key){
    advanceRevision();
    m_inputGeneration = __hidden_ui_radio_group_state::NextIdentity();
    m_selected = key;
    m_cursor = key;
}

void RadioGroupState::reset(){
    advanceRevision();
    m_inputGeneration = __hidden_ui_radio_group_state::NextIdentity();
    m_selected = 0u;
    m_cursor = 0u;
    m_sourceGeneration = 0u;
    m_sourceRevision = 0u;
    m_placement = {};
}


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


void RadioGroupState::advanceRevision(){
    if(m_revision == Limit<u64>::s_Max)
        TerminateInvariant();
    ++m_revision;
}


