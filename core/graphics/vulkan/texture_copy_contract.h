namespace TextureCopyQueueRequirement{
    static constexpr u8 s_TextureCopyQueueRequirementTransferBase = 0u;
    enum Enum : u8{
        Transfer = s_TextureCopyQueueRequirementTransferBase,
        ComputeOrGraphics,
        Graphics,
    };
};

