namespace EditAction{
    enum Enum : u8{ Submit, Cancel, Blur, Abandon };
};

// Actions run between copied input events while the matching model is lent. Neither reference may be retained.
struct IEditActionSink : private NoCopy{
public:
    virtual ~IEditActionSink()noexcept = default;


public:
    // False rejects the borrowed transaction; an invalid draft may still accept an action without committing a value.
    [[nodiscard]] virtual bool apply(EditModel& draft, EditAction::Enum action, bool readOnly) = 0;
};


