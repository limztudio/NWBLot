[[nodiscard]] inline const Core::GpuPhysicalQueueInfo* QueueForTask(
    const Core::GpuTaskRecordContext& context,
    const Core::GpuTaskId* const task
){
    if(!task || !task->valid())
        return nullptr;
    return context.graph.queueInfoForTask(*task);
}


