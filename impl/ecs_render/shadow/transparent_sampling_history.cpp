void TransparentShadowSamplingHistory::reset()noexcept{
    m_acceptedSlots = 0u;
    m_pendingSlots = 0u;
}

void TransparentShadowSamplingHistory::accept()noexcept{
    m_acceptedSlots = m_pendingSlots;
    m_pendingSlots = 0u;
}


