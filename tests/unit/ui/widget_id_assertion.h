// Assert valid widget IDs and return a fallback ID only after recording a test failure.
[[nodiscard]] inline NWB::Impl::Ui::WidgetId RequireWidgetId(const Expected<NWB::Impl::Ui::WidgetId>& result){
    EXPECT_TRUE(result);
    if(!result)
        return {};
    return *result;
}


