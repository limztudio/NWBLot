SIMDVectorDouble InsetUiRectValue(const Rect& bounds, const Insets& padding)noexcept{
    const Double4 inset = ComputeInsetUiRectBounds(bounds, padding);
    return VectorDoubleSet(inset.x, inset.y, inset.z, inset.w);
}


