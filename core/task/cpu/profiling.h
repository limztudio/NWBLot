namespace CpuTaskProfileKind{
    enum Enum : u8{
        QueueDelay,
        Execution,
        HandleJoin,
        ScopeJoin,
        SchedulerJoin,
        WorkerIdle,
    };
};

struct CpuTaskProfileEvent{
    CpuTaskProfileKind::Enum kind = CpuTaskProfileKind::Execution;
    CpuTaskHandle task;
    Name label;
    u64 durationNanoseconds = 0u;
    u64 frameIndex = 0u;
    u64 captureEpoch = 0u;
    usize workerIndex = 0u;
    CpuAffinity::Enum affinity = CpuAffinity::Any;
};


