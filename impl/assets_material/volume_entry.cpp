static Expected<MaterialCookEntry> ParseMaterialDocument(
    const Path& assetRoot,
    const AStringView virtualRoot,
    const Path& nwbFilePath,
    const Core::Metascript::Document& doc,
    Core::Assets::CookEntryParseContext& context
){
    return ParseMaterialCookMetadata(
        assetRoot,
        virtualRoot,
        nwbFilePath,
        doc,
        context.cookArena,
        context.scratchArena
    );
}

static bool RegisterMaterialCookEntry(Core::Assets::CookEntryRegistry& registry){
    return Core::Assets::RegisterSingleDocumentCookEntry<MaterialCookEntry, Material, MaterialAssetCodec>(
        registry,
        NWB_TEXT("material"),
        &ParseMaterialDocument,
        [](MaterialCookEntry& entry, Core::Assets::AssetArena& arena){ return Core::Assets::ForwardCookBuild(entry, arena, &BuildMaterialAsset); },
        false
    );
}


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


NWB_DEFINE_COOK_ENTRY_REGISTRAR(s_MaterialCookEntryRegistrar, RegisterMaterialCookEntry);


