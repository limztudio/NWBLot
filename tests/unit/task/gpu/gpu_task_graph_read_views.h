namespace Tests{


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


struct GpuTaskGraphReadViews final : NoCopy{
    Core::GpuTaskGraph::DeclarationReadView declarations;
    Core::GpuCompiledGraph::ReadView compiled;


public:
    GpuTaskGraphReadViews(const Core::GpuTaskGraph& graph, const Core::GpuCompiledGraph& compiledGraph)noexcept
        : declarations(graph)
        , compiled(compiledGraph)
    {}


public:
    [[nodiscard]] b8 valid()const noexcept{
        return declarations.valid() && compiled.valid() && compiled.validFor(declarations);
    }
};


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


};


