static b8 RegisterFontCookEntry(Core::Assets::CookEntryRegistry& registry){
    return Core::Assets::RegisterDocumentValueCookEntry<FontCookEntry, Font, FontAssetCodec>(
        FontBinaryPayload::s_FontAssetKindLabel,
        [](const Path& root, AStringView virtualRoot, const Path& path, const Core::Metascript::Document& doc, Core::Assets::CookEntryParseContext& context){
            return ParseFontCookMetadata(root, virtualRoot, path, doc, context.cookArena, context.scratchArena);
        },
        [](Name virtualPath, const Path& path, const Core::Metascript::Value& asset, Core::Assets::CookEntryParseContext& context){
            return ParseFontCookMetadataValue(virtualPath, path, asset, context.cookArena);
        },
        [](FontCookEntry& entry, Core::Assets::AssetArena& arena, Core::Alloc::ScratchArena&){ return BuildFontAsset(Move(entry), arena); },
        false,
        registry
    );
}


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


NWB_DEFINE_COOK_ENTRY_REGISTRAR(s_FontCookEntryRegistrar, RegisterFontCookEntry);


