u64 Append(u64 hash, u8 byte){
    return (hash ^ byte) * 1099511628211ull;
}

u64 AppendInteger(u64 hash, const u64 value){
    for(u32 index = 0u; index < 8u; ++index)
        hash = Append(hash, static_cast<u8>(value >> (index * 8u)));
    return hash;
}


