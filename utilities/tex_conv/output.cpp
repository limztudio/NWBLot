bool CheckOutputPath(const Path& path, const bool force, const bool temporary){
    ErrorCode errorCode;
    const bool exists = FileExistsNoFollow(path, errorCode);
    if(errorCode){
        NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: failed to query output path '{}': {}")
            , PathToString<tchar>(path)
            , StringConvert(errorCode.message())
        );
        return false;
    }
    if(!exists)
        return true;

    const bool regular = IsRegularFile(path, errorCode);
    if(errorCode){
        NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: failed to inspect output path '{}': {}")
            , PathToString<tchar>(path)
            , StringConvert(errorCode.message())
        );
        return false;
    }
    if(!regular){
        NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: output path is not a regular file: '{}'"), PathToString<tchar>(path));
        return false;
    }
    if(temporary){
        NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: publication work path already exists: '{}'"), PathToString<tchar>(path));
        return false;
    }
    if(!force){
        NWB_LOGGER_ERROR(NWB_TEXT("tex_conv: Output already exists: '{}'. Pass --force to replace both output files.")
            , PathToString<tchar>(path)
        );
        return false;
    }

    return true;
}

AString BuildMetadata(const TexturePayload& payload, const Path& dataPath){
    AStringStream output;
    const AString dataName = MakeJsonEscapedText<AString>(PathToGenericString<AString>(dataPath.filename()));
    const bool hdr = payload.format == TexturePayloadFormat::UastcHdr4x4;
    const AStringView formatName = hdr ? TextureFormat::s_UastcHdr4x4Format : TextureFormat::s_UastcLdr4x4Format;
    if(
        (payload.format != TexturePayloadFormat::UastcLdr4x4 && payload.format != TexturePayloadFormat::UastcHdr4x4)
        || (!hdr && (!payload.alphaBytes.empty() || payload.alphaMode == TextureAlphaMode::SeparateUastcLdr4x4))
        || (hdr && payload.srgb)
        || (hdr && payload.hasAlpha != (payload.alphaMode != TextureAlphaMode::Opaque))
        || (hdr && payload.alphaMode == TextureAlphaMode::EmbeddedLdr)
        || (hdr && payload.alphaMode == TextureAlphaMode::SeparateUastcLdr4x4 && payload.alphaBytes.size() != payload.bytes.size())
        || (hdr && payload.alphaMode != TextureAlphaMode::SeparateUastcLdr4x4 && !payload.alphaBytes.empty())
        || (hdr && payload.alphaMode != TextureAlphaMode::ConstantUnorm8 && payload.alphaConstantUnorm8 != TextureFormat::s_OpaqueAlphaUnorm8)
    )
        return {};
    const AStringView dimensionName = payload.dimension == TextureDimension::TextureCube
        ? TextureFormat::s_TextureCubeDimension
        : payload.dimension == TextureDimension::Texture3D
            ? TextureFormat::s_Texture3DDimension
            : TextureFormat::s_Texture2DDimension
    ;
    output
        << "// Generated by tex_conv. The referenced .tex file is a contiguous raw "
        << (hdr ? "UASTC HDR RGB block stream, optionally followed by a matched UASTC LDR alpha stream." : "UASTC LDR block stream.") << s_NewLine
        << "texture asset;" << s_NewLine
        << s_NewLine
        << "asset.format = \"" << formatName << "\";" << s_NewLine
    ;
    if(!hdr)
        output << "asset.color_space = \"" << (payload.srgb ? TextureFormat::s_SrgbColorSpace : TextureFormat::s_LinearColorSpace) << "\";" << s_NewLine;
    output << "asset.dimension = \"" << dimensionName << "\";" << s_NewLine;
    if(payload.dimension == TextureDimension::Texture3D)
        output << "asset.depth = " << payload.depth << ";" << s_NewLine;
    output
        << "asset.width = " << payload.width << ";" << s_NewLine
        << "asset.height = " << payload.height << ";" << s_NewLine
    ;
    if(!hdr)
        output << "asset.has_alpha = " << (payload.hasAlpha ? 1 : 0) << ";" << s_NewLine;
    else{
        switch(payload.alphaMode){
        case TextureAlphaMode::Opaque:
            output << "asset.alpha_mode = \"" << TextureFormat::s_AlphaOpaqueMode << "\";" << s_NewLine;
            break;
        case TextureAlphaMode::ConstantUnorm8:
            output
                << "asset.alpha_mode = \"" << TextureFormat::s_AlphaConstantUnorm8Mode << "\";" << s_NewLine
                << "asset.alpha_constant_unorm8 = " << static_cast<u32>(payload.alphaConstantUnorm8) << ";" << s_NewLine
            ;
            break;
        case TextureAlphaMode::SeparateUastcLdr4x4:
            output << "asset.alpha_mode = \"" << TextureFormat::s_AlphaUastcLdr4x4Mode << "\";" << s_NewLine;
            break;
        default:
            return {};
        }
    }
    output << "asset.data = \"" << dataName << "\";" << s_NewLine;
    return output.str();
}

[[nodiscard]] bool StageOutput(
    const Path& path,
    const void* const data,
    const usize count,
    const void* const tail,
    const usize tailCount,
    bool& outOwned)noexcept{
#if defined(NWB_PLATFORM_WINDOWS)
    const HANDLE handle = CreateFile(path.c_str(), GENERIC_WRITE, 0u, nullptr, CREATE_NEW, FILE_ATTRIBUTE_NORMAL, nullptr);
    if(handle == INVALID_HANDLE_VALUE)
        return false;
    outOwned = true;
    const bool written = WriteAllWin32Handle(handle, data, count) && WriteAllWin32Handle(handle, tail, tailCount);
    const bool flushed = written && FlushFileBuffers(handle);
    const bool closed = CloseHandle(handle);
#else
    const int descriptor = open(path.c_str(), O_WRONLY | O_CREAT | O_EXCL | O_CLOEXEC, 0666u);
    if(descriptor < 0)
        return false;
    outOwned = true;
    const bool written = WriteAllFileDescriptor(descriptor, data, count) && WriteAllFileDescriptor(descriptor, tail, tailCount);
    const bool flushed = written && fsync(descriptor) == 0;
    const bool closed = close(descriptor) == 0;
#endif
    return written && flushed && closed;
}

void CaptureCleanupFailure(const Path& path, const ErrorCode& error)noexcept{
    const DiagnosticEventText diagnostic = MakeDiagnosticEventText(
        "tex_conv: publication cleanup failed for '{}', error {}",
        path.c_str(),
        error.value()
    );
    CaptureDiagnosticEvent("tex_conv_publication", diagnostic.view(), __FILE__, __LINE__);
}


