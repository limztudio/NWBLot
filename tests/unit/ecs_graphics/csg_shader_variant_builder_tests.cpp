using namespace NWB;
using namespace NWB::Impl;


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


TEST(CsgShaderVariantBuilderTests, RejectsMalformedSegmentsAndEmptyAssignmentValues){
    const CsgShaderVariantBuilder builder;
    EXPECT_FALSE(builder.findDefineAssignment("default", "MODE", "default"));
    EXPECT_FALSE(builder.findDefineAssignment("BROKEN;MODE=1", "MODE", "default"));
    EXPECT_FALSE(builder.findDefineAssignment("MODE=;OTHER=2", "MODE", "default"));
    const auto found = builder.findDefineAssignment("FIRST=0;MODE=1;OTHER=2", "MODE", "default");
    ASSERT_TRUE(found);
    EXPECT_EQ(*found, AStringView("MODE=1"));
}


