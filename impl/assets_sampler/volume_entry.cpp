static Expected<SamplerCookEntry> ParseSamplerDocument(
    const Path& assetRoot,
    const AStringView virtualRoot,
    const Path& nwbFilePath,
    const Core::Metascript::Document& doc,
    Core::Assets::CookEntryParseContext& context
){
    return ParseSamplerCookMetadata(
        assetRoot,
        virtualRoot,
        nwbFilePath,
        doc,
        context.cookArena,
        context.scratchArena
    );
}

static bool RegisterSamplerCookEntry(Core::Assets::CookEntryRegistry& registry){
    return Core::Assets::RegisterSingleDocumentCookEntry<SamplerCookEntry, Sampler, SamplerAssetCodec>(
        registry,
        NWB_TEXT("sampler"),
        &ParseSamplerDocument,
        [](SamplerCookEntry& entry, Core::Assets::AssetArena& arena){ return Core::Assets::ForwardCookBuild(entry, arena, &BuildSamplerAsset); },
        false
    );
}


////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////


NWB_DEFINE_COOK_ENTRY_REGISTRAR(s_SamplerCookEntryRegistrar, RegisterSamplerCookEntry);


